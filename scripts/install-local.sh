#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
INSTALL_ROOT="${WAYPOINT_INSTALL_ROOT:-$HOME/.local/share/logbook-waypoint}"
BIN_DIR="${WAYPOINT_BIN_DIR:-$HOME/.local/bin}"
BIN_PATH="$BIN_DIR/waypoint"
RELEASE_DIR="$INSTALL_ROOT/releases/local"
EXTENSION_DIR="${WAYPOINT_LOCAL_EXTENSION_DIR:-$INSTALL_ROOT/local-extension}"
INSTALL_SKILL=1
OPEN_FINDER=1
RESTART_SERVER=1

usage() {
  cat <<'USAGE'
Usage: scripts/install-local.sh [options]

Builds this checkout and installs it as your local Waypoint:
  - copies the extension build to a stable folder for "Load unpacked"
  - replaces the installer-managed `waypoint` CLI with this checkout's build
  - installs this checkout's Waypoint skill globally
  - restarts a running Waypoint server on the new build

Run `waypoint update` to return to the latest published release.

Options:
  --skip-skill   Keep the currently installed Waypoint skill
  --no-open      Do not reveal the extension folder in Finder
  --no-restart   Leave a running Waypoint server on its current build
  -h, --help     Show this help
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --skip-skill) INSTALL_SKILL=0; shift ;;
    --no-open) OPEN_FINDER=0; shift ;;
    --no-restart) RESTART_SERVER=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'waypoint: unknown option %s\n' "$1" >&2; usage >&2; exit 1 ;;
  esac
done

info() {
  printf '\033[1;36m%s\033[0m %s\n' "waypoint" "$1"
}

fail() {
  printf 'waypoint: %s\n' "$1" >&2
  exit 1
}

if [[ -e "$BIN_PATH" || -L "$BIN_PATH" ]] && ! grep -q "Generated by Logbook Waypoint install.sh" "$BIN_PATH" 2>/dev/null; then
  fail "$BIN_PATH was not written by the Waypoint installer; remove it or install with npm from this checkout instead"
fi

command -v pnpm >/dev/null 2>&1 || fail "pnpm is required"
command -v rsync >/dev/null 2>&1 || fail "rsync is required"

source_ref="$(git -C "$ROOT_DIR" rev-parse --short HEAD 2>/dev/null || printf 'unknown')"
if [[ -n "$(git -C "$ROOT_DIR" status --porcelain 2>/dev/null)" ]]; then
  source_ref="$source_ref+dirty"
fi

info "installing dependencies"
pnpm --dir "$ROOT_DIR" install --frozen-lockfile

info "building the extension"
CI=1 pnpm --dir "$ROOT_DIR" --filter @logbookfordevs/waypoint-extension build
mkdir -p "$EXTENSION_DIR"
rsync -a --delete "$ROOT_DIR/packages/extension/.output/chrome-mv3/" "$EXTENSION_DIR/"

tmp_dir="$(mktemp -d)"
cleanup() { rm -rf "$tmp_dir"; }
trap cleanup EXIT

info "packaging the CLI"
WAYPOINT_RELEASE_OUT_DIR="$tmp_dir" "$ROOT_DIR/scripts/package-waypoint-release.sh"
rm -rf "$RELEASE_DIR"
mkdir -p "$RELEASE_DIR" "$BIN_DIR"
tar -xzf "$tmp_dir/waypoint-cli.tar.gz" -C "$RELEASE_DIR"

printf -v escaped_entry_path '%q' "$RELEASE_DIR/bin/cli.js"
cat > "$BIN_PATH" <<LAUNCHER
#!/usr/bin/env bash
set -euo pipefail
# Generated by Logbook Waypoint install.sh.
WAYPOINT_ENTRYPOINT=$escaped_entry_path

if ! command -v node >/dev/null 2>&1; then
  printf 'waypoint: node >=22.12.0 is required to run Logbook Waypoint.\n' >&2
  exit 1
fi

exec node "\$WAYPOINT_ENTRYPOINT" "\$@"
LAUNCHER
chmod +x "$BIN_PATH"

node --input-type=module - "$RELEASE_DIR" "$INSTALL_ROOT" "$BIN_DIR" "$ROOT_DIR" "$source_ref" <<'METADATA'
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
const [releaseDir, root, bin, checkout, ref] = process.argv.slice(2);
writeFileSync(join(releaseDir, '.waypoint-install.json'), JSON.stringify({
  channel: 'github', installRoot: resolve(root), binDir: resolve(bin), repo: 'logbookfordevs/logbook-waypoint', asset: 'waypoint-cli.tar.gz',
}));
writeFileSync(join(releaseDir, '.waypoint-local-source.json'), JSON.stringify({ checkout, ref, installedAt: new Date().toISOString() }, null, 2));
METADATA
info "installed $BIN_PATH from $source_ref"

if [[ "$INSTALL_SKILL" -eq 1 ]]; then
  info "installing this checkout's Waypoint skill globally"
  npx --yes skills@latest add "$RELEASE_DIR/skills/waypoint" --global --agent universal --skill waypoint --yes </dev/null \
    || info "skill installation did not complete; the CLI and extension are still installed"
fi

if [[ "$RESTART_SERVER" -eq 1 ]] && "$BIN_PATH" status 2>/dev/null | grep -q "Server is running"; then
  info "restarting the running server on the local build"
  "$BIN_PATH" restart
fi

printf '\n'
info "local build $source_ref is ready."
printf '\n  Extension   %s\n' "$EXTENSION_DIR"
printf '              First time: chrome://extensions > Developer mode > Load unpacked > this folder.\n'
printf '              After that: press reload on the Waypoint card; the folder path never changes.\n'
printf '  CLI         %s -> %s\n' "$BIN_PATH" "$RELEASE_DIR"
printf '  Go back     waypoint update\n\n'

if [[ "$OPEN_FINDER" -eq 1 && "$(uname -s)" = "Darwin" ]]; then
  printf '%s' "$EXTENSION_DIR" | pbcopy 2>/dev/null || true
  open -R "$EXTENSION_DIR"
fi
